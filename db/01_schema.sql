-- ---------------------------------------------------------------------
-- APP_USER : students, outlet vendors and administrators
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
  user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  full_name       VARCHAR2(80)   NOT NULL,
  email           VARCHAR2(120)  NOT NULL,
  phone           VARCHAR2(15),
  reg_no          VARCHAR2(20),
  password_hash   VARCHAR2(200)  NOT NULL,
  role            VARCHAR2(10)   DEFAULT 'STUDENT' NOT NULL,
  wallet_balance  NUMBER(10,2)   DEFAULT 0 NOT NULL,
  loyalty_points  NUMBER(8)      DEFAULT 0 NOT NULL,
  is_active       CHAR(1)        DEFAULT 'Y' NOT NULL,
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_app_user        PRIMARY KEY (user_id),
  CONSTRAINT uq_app_user_email  UNIQUE (email),
  CONSTRAINT uq_app_user_regno  UNIQUE (reg_no),
  CONSTRAINT ck_app_user_role   CHECK (role IN ('STUDENT','VENDOR','ADMIN')),
  CONSTRAINT ck_app_user_wallet CHECK (wallet_balance >= 0),
  CONSTRAINT ck_app_user_points CHECK (loyalty_points >= 0),
  CONSTRAINT ck_app_user_active CHECK (is_active IN ('Y','N')),
  CONSTRAINT ck_app_user_email  CHECK (REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
  CONSTRAINT ck_app_user_phone  CHECK (phone IS NULL OR REGEXP_LIKE(phone, '^[0-9]{10}$'))
);

-- ---------------------------------------------------------------------
-- OUTLET : a food counter / canteen on campus, managed by one vendor
-- ---------------------------------------------------------------------
CREATE TABLE outlet (
  outlet_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  name            VARCHAR2(80)   NOT NULL,
  location        VARCHAR2(120)  NOT NULL,
  owner_id        NUMBER         NOT NULL,
  open_time       VARCHAR2(5)    DEFAULT '08:00' NOT NULL,
  close_time      VARCHAR2(5)    DEFAULT '22:00' NOT NULL,
  is_open         CHAR(1)        DEFAULT 'Y' NOT NULL,
  parallel_slots  NUMBER(2)      DEFAULT 2 NOT NULL,
  slot_capacity   NUMBER(3)      DEFAULT 8 NOT NULL,
  tagline         VARCHAR2(120),
  cover_url       VARCHAR2(300),
  CONSTRAINT pk_outlet        PRIMARY KEY (outlet_id),
  CONSTRAINT uq_outlet_name   UNIQUE (name),
  CONSTRAINT fk_outlet_owner  FOREIGN KEY (owner_id) REFERENCES app_user(user_id),
  CONSTRAINT ck_outlet_open   CHECK (is_open IN ('Y','N')),
  CONSTRAINT ck_outlet_slots  CHECK (parallel_slots BETWEEN 1 AND 20),
  CONSTRAINT ck_outlet_cap    CHECK (slot_capacity BETWEEN 1 AND 200),
  CONSTRAINT ck_outlet_otime  CHECK (REGEXP_LIKE(open_time,  '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
  CONSTRAINT ck_outlet_ctime  CHECK (REGEXP_LIKE(close_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))
);

-- ---------------------------------------------------------------------
-- CATEGORY : menu categories shared by all outlets
-- ---------------------------------------------------------------------
CREATE TABLE category (
  category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  name            VARCHAR2(40)   NOT NULL,
  CONSTRAINT pk_category      PRIMARY KEY (category_id),
  CONSTRAINT uq_category_name UNIQUE (name)
);

-- ---------------------------------------------------------------------
-- MENU_ITEM : dishes sold by an outlet
-- ---------------------------------------------------------------------
CREATE TABLE menu_item (
  item_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  outlet_id       NUMBER         NOT NULL,
  category_id     NUMBER         NOT NULL,
  name            VARCHAR2(80)   NOT NULL,
  description     VARCHAR2(300),
  price           NUMBER(8,2)    NOT NULL,
  is_veg          CHAR(1)        DEFAULT 'Y' NOT NULL,
  stock_qty       NUMBER(6)      DEFAULT 0 NOT NULL,
  prep_minutes    NUMBER(3)      DEFAULT 10 NOT NULL,
  is_available    CHAR(1)        DEFAULT 'Y' NOT NULL,
  rating_avg      NUMBER(3,2)    DEFAULT 0 NOT NULL,
  rating_count    NUMBER(8)      DEFAULT 0 NOT NULL,
  image_url       VARCHAR2(300),
  CONSTRAINT pk_menu_item         PRIMARY KEY (item_id),
  CONSTRAINT uq_menu_item_name    UNIQUE (outlet_id, name),
  CONSTRAINT fk_menu_item_outlet  FOREIGN KEY (outlet_id)   REFERENCES outlet(outlet_id) ON DELETE CASCADE,
  CONSTRAINT fk_menu_item_cat     FOREIGN KEY (category_id) REFERENCES category(category_id),
  CONSTRAINT ck_menu_item_price   CHECK (price > 0),
  CONSTRAINT ck_menu_item_veg     CHECK (is_veg IN ('Y','N')),
  CONSTRAINT ck_menu_item_stock   CHECK (stock_qty >= 0),
  CONSTRAINT ck_menu_item_prep    CHECK (prep_minutes BETWEEN 1 AND 120),
  CONSTRAINT ck_menu_item_avail   CHECK (is_available IN ('Y','N')),
  CONSTRAINT ck_menu_item_rating  CHECK (rating_avg BETWEEN 0 AND 5)
);

-- ---------------------------------------------------------------------
-- COUPON : discount codes
-- ---------------------------------------------------------------------
CREATE TABLE coupon (
  code            VARCHAR2(20),
  discount_pct    NUMBER(5,2)    NOT NULL,
  max_discount    NUMBER(8,2)    NOT NULL,
  min_order       NUMBER(8,2)    DEFAULT 0 NOT NULL,
  valid_from      DATE           NOT NULL,
  valid_to        DATE           NOT NULL,
  usage_limit     NUMBER(6)      DEFAULT 100 NOT NULL,
  used_count      NUMBER(6)      DEFAULT 0 NOT NULL,
  CONSTRAINT pk_coupon        PRIMARY KEY (code),
  CONSTRAINT ck_coupon_pct    CHECK (discount_pct > 0 AND discount_pct <= 100),
  CONSTRAINT ck_coupon_dates  CHECK (valid_to >= valid_from),
  CONSTRAINT ck_coupon_usage  CHECK (used_count <= usage_limit)
);

-- ---------------------------------------------------------------------
-- PICKUP_SLOT : 15-minute pickup windows with a booking limit.
-- Rows are created on demand by TRG_ORDER_SLOT; the CHECK constraint
-- makes overbooking impossible even under concurrent orders.
-- ---------------------------------------------------------------------
CREATE TABLE pickup_slot (
  outlet_id       NUMBER         NOT NULL,
  slot_start      DATE           NOT NULL,
  capacity        NUMBER(3)      NOT NULL,
  booked          NUMBER(3)      DEFAULT 0 NOT NULL,
  CONSTRAINT pk_pickup_slot      PRIMARY KEY (outlet_id, slot_start),
  CONSTRAINT fk_pickup_slot_out  FOREIGN KEY (outlet_id) REFERENCES outlet(outlet_id) ON DELETE CASCADE,
  CONSTRAINT ck_pickup_slot_bkd  CHECK (booked BETWEEN 0 AND capacity),
  CONSTRAINT ck_pickup_slot_15   CHECK (MOD(TO_NUMBER(TO_CHAR(slot_start, 'MI')), 15) = 0
                                        AND TO_CHAR(slot_start, 'SS') = '00')
);

-- ---------------------------------------------------------------------
-- ORDERS : one pre-order placed by a student at one outlet
-- ---------------------------------------------------------------------
CREATE TABLE orders (
  order_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id         NUMBER         NOT NULL,
  outlet_id       NUMBER         NOT NULL,
  token_no        NUMBER(5),
  pickup_code     VARCHAR2(6),
  status          VARCHAR2(12)   DEFAULT 'PLACED' NOT NULL,
  subtotal        NUMBER(10,2)   DEFAULT 0 NOT NULL,
  discount        NUMBER(10,2)   DEFAULT 0 NOT NULL,
  tax             NUMBER(10,2)   DEFAULT 0 NOT NULL,
  total_amount    NUMBER(10,2)   DEFAULT 0 NOT NULL,
  coupon_code     VARCHAR2(20),
  pickup_slot     DATE,
  notes           VARCHAR2(200),
  placed_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  picked_up_at    TIMESTAMP,
  updated_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_orders         PRIMARY KEY (order_id),
  CONSTRAINT fk_orders_user    FOREIGN KEY (user_id)     REFERENCES app_user(user_id),
  CONSTRAINT fk_orders_outlet  FOREIGN KEY (outlet_id)   REFERENCES outlet(outlet_id),
  CONSTRAINT fk_orders_coupon  FOREIGN KEY (coupon_code) REFERENCES coupon(code),
  CONSTRAINT fk_orders_slot    FOREIGN KEY (outlet_id, pickup_slot) REFERENCES pickup_slot(outlet_id, slot_start),
  CONSTRAINT ck_orders_code    CHECK (pickup_code IS NULL OR REGEXP_LIKE(pickup_code, '^[0-9]{6}$')),
  CONSTRAINT ck_orders_status  CHECK (status IN ('PLACED','ACCEPTED','PREPARING','READY','PICKED_UP','CANCELLED')),
  CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount >= 0 AND tax >= 0 AND total_amount >= 0)
);

-- ---------------------------------------------------------------------
-- ORDER_ITEM : lines of an order (weak entity of ORDERS)
-- ---------------------------------------------------------------------
CREATE TABLE order_item (
  order_id        NUMBER         NOT NULL,
  item_id         NUMBER         NOT NULL,
  qty             NUMBER(3)      NOT NULL,
  unit_price      NUMBER(8,2)    NOT NULL,
  line_total      NUMBER(10,2)   NOT NULL,
  CONSTRAINT pk_order_item        PRIMARY KEY (order_id, item_id),
  CONSTRAINT fk_order_item_order  FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE,
  CONSTRAINT fk_order_item_item   FOREIGN KEY (item_id)  REFERENCES menu_item(item_id),
  CONSTRAINT ck_order_item_qty    CHECK (qty BETWEEN 1 AND 20)
);

-- ---------------------------------------------------------------------
-- WALLET_TXN : ledger of every wallet movement
-- ---------------------------------------------------------------------
CREATE TABLE wallet_txn (
  txn_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id         NUMBER         NOT NULL,
  txn_type        VARCHAR2(10)   NOT NULL,
  amount          NUMBER(10,2)   NOT NULL,
  balance_after   NUMBER(10,2)   NOT NULL,
  order_id        NUMBER,
  remarks         VARCHAR2(120),
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_wallet_txn        PRIMARY KEY (txn_id),
  CONSTRAINT fk_wallet_txn_user   FOREIGN KEY (user_id)  REFERENCES app_user(user_id),
  CONSTRAINT fk_wallet_txn_order  FOREIGN KEY (order_id) REFERENCES orders(order_id),
  CONSTRAINT ck_wallet_txn_type   CHECK (txn_type IN ('TOPUP','DEBIT','REFUND')),
  CONSTRAINT ck_wallet_txn_amt    CHECK (amount > 0)
);

-- ---------------------------------------------------------------------
-- ORDER_STATUS_LOG : audit trail written by trigger
-- ---------------------------------------------------------------------
CREATE TABLE order_status_log (
  log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  order_id        NUMBER         NOT NULL,
  old_status      VARCHAR2(12),
  new_status      VARCHAR2(12)   NOT NULL,
  changed_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_order_status_log  PRIMARY KEY (log_id),
  CONSTRAINT fk_osl_order         FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- TOKEN_COUNTER : per-outlet, per-day pickup token sequence
-- ---------------------------------------------------------------------
CREATE TABLE token_counter (
  outlet_id       NUMBER         NOT NULL,
  token_date      DATE           NOT NULL,
  last_token      NUMBER(5)      DEFAULT 0 NOT NULL,
  CONSTRAINT pk_token_counter  PRIMARY KEY (outlet_id, token_date),
  CONSTRAINT fk_token_outlet   FOREIGN KEY (outlet_id) REFERENCES outlet(outlet_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- REVIEW : rating of an item from a completed order
-- ---------------------------------------------------------------------
CREATE TABLE review (
  review_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  order_id        NUMBER         NOT NULL,
  item_id         NUMBER         NOT NULL,
  user_id         NUMBER         NOT NULL,
  rating          NUMBER(1)      NOT NULL,
  comments        VARCHAR2(300),
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_review         PRIMARY KEY (review_id),
  CONSTRAINT uq_review_line    UNIQUE (order_id, item_id),
  CONSTRAINT fk_review_line    FOREIGN KEY (order_id, item_id) REFERENCES order_item(order_id, item_id) ON DELETE CASCADE,
  CONSTRAINT fk_review_user    FOREIGN KEY (user_id) REFERENCES app_user(user_id),
  CONSTRAINT ck_review_rating  CHECK (rating BETWEEN 1 AND 5)
);

-- ---------------------------------------------------------------------
-- PRICE_HISTORY : price changes captured by trigger
-- ---------------------------------------------------------------------
CREATE TABLE price_history (
  history_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  item_id         NUMBER         NOT NULL,
  old_price       NUMBER(8,2)    NOT NULL,
  new_price       NUMBER(8,2)    NOT NULL,
  changed_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_price_history  PRIMARY KEY (history_id),
  CONSTRAINT fk_ph_item        FOREIGN KEY (item_id) REFERENCES menu_item(item_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- STOCK_ALERT : raised by trigger when stock runs low
-- ---------------------------------------------------------------------
CREATE TABLE stock_alert (
  alert_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  item_id         NUMBER         NOT NULL,
  stock_qty       NUMBER(6)      NOT NULL,
  is_resolved     CHAR(1)        DEFAULT 'N' NOT NULL,
  created_at      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_stock_alert   PRIMARY KEY (alert_id),
  CONSTRAINT fk_sa_item       FOREIGN KEY (item_id) REFERENCES menu_item(item_id) ON DELETE CASCADE,
  CONSTRAINT ck_sa_resolved   CHECK (is_resolved IN ('Y','N'))
);

-- ---------------------------------------------------------------------
-- DAILY_SALES_SUMMARY : filled by a cursor-based procedure
-- ---------------------------------------------------------------------
CREATE TABLE daily_sales_summary (
  summary_date    DATE           NOT NULL,
  outlet_id       NUMBER         NOT NULL,
  total_orders    NUMBER(6)      NOT NULL,
  cancelled_orders NUMBER(6)     NOT NULL,
  items_sold      NUMBER(8)      NOT NULL,
  gross_revenue   NUMBER(12,2)   NOT NULL,
  top_item_id     NUMBER,
  generated_at    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_daily_sales    PRIMARY KEY (summary_date, outlet_id),
  CONSTRAINT fk_ds_outlet      FOREIGN KEY (outlet_id)   REFERENCES outlet(outlet_id) ON DELETE CASCADE,
  CONSTRAINT fk_ds_item        FOREIGN KEY (top_item_id) REFERENCES menu_item(item_id)
);

-- Indexes on foreign keys / frequent filters
CREATE INDEX ix_menu_item_outlet  ON menu_item(outlet_id, category_id);
CREATE INDEX ix_orders_user       ON orders(user_id, placed_at);
CREATE INDEX ix_orders_outlet     ON orders(outlet_id, status);
CREATE INDEX ix_orders_slot       ON orders(outlet_id, pickup_slot);

-- Row type returned by the pipelined function canteen_pkg.get_slots
CREATE OR REPLACE TYPE t_slot_row AS OBJECT (
  slot_start  DATE,
  capacity    NUMBER,
  booked      NUMBER,
  available   NUMBER
);
/
CREATE OR REPLACE TYPE t_slot_tab AS TABLE OF t_slot_row;
/
CREATE INDEX ix_wallet_txn_user   ON wallet_txn(user_id, created_at);
CREATE INDEX ix_osl_order         ON order_status_log(order_id);
CREATE INDEX ix_stock_alert_open  ON stock_alert(is_resolved, item_id);
